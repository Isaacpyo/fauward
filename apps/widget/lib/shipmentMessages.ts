const CATALOGS: Record<string, MessageCatalog> = {
  en,
  fr,
  ar,
};

function languageKey(locale: string): string {
  return locale.toLowerCase().split("-")[0] ?? "en";
}

export function createTranslator(locale: string) {
  const catalog = CATALOGS[languageKey(locale)] ?? en;
  return function t(key: string, values?: Record<string, string | number>) {
    const template = catalog[key] ?? en[key] ?? key;
    if (!values) return template;
    return Object.entries(values).reduce(
      (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
      template,
    );
  };
}
